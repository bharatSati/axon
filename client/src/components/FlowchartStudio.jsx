/**
 * Robust sanitizer that fixes common Mermaid.js syntax errors generated by LLMs.
 * E.g., duplicate flowchart headers, emojis outside quotes, unquoted labels with parens.
 */
function sanitizeMermaidCode(rawCode, orientation = "TD") {
  if (!rawCode) return "";
  let code = rawCode;

  // 1. Strip markdown bold and italic markers
  code = code.replace(/\*\*/g, "").replace(/(?<!\w)\*(?!\w)/g, "");

  // 2. Strip any code fence wrappers
  let lines = code
    .split("\n")
    .map((l) => l.replace(/```(?:mermaid)?/gi, "").trimEnd())
    .filter((l) => {
      const t = l.trim();
      return !t.startsWith("```") && t !== "%%" && !t.includes("```mermaid");
    });

  // 3. Detect and deduplicate diagram header declarations
  const headerRegex = /^\s*(flowchart\s+(?:TD|TB|BT|RL|LR)|graph\s+(?:TD|TB|BT|RL|LR)|sequenceDiagram|classDiagram|erDiagram|stateDiagram-v2|stateDiagram)\b/i;
  let firstHeaderIndex = -1;
  let detectedHeader = `flowchart ${orientation}`;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (headerRegex.test(line)) {
      if (firstHeaderIndex === -1) {
        firstHeaderIndex = i;
        detectedHeader = line;
      } else {
        // Subsequent duplicate header! Remove it completely to prevent parse error!
        lines[i] = "";
      }
    }
  }

  // Ensure ONE header exists and is positioned at top
  if (firstHeaderIndex === -1) {
    lines.unshift(`flowchart ${orientation}`);
  } else if (firstHeaderIndex > 0) {
    const h = lines[firstHeaderIndex];
    lines.splice(firstHeaderIndex, 1);
    lines.unshift(h);
  }

  let hasEncounteredHeader = false;

  const cleaned = lines.map((line) => {
    let l = line;
    const trimmed = l.trim();

    // Check diagram declaration
    if (headerRegex.test(trimmed)) {
      if (!hasEncounteredHeader) {
        hasEncounteredHeader = true;
        return trimmed;
      } else {
        return "";
      }
    }

    // Pattern A: Leading emoji or text outside quotes:
    // nodeId[🟦 "Click Login with GitHub"] -> nodeId["🟦 Click Login with GitHub"]
    // Supports shapes: [ ], ( ), { }, ([ ]), [( )], [[ ]], {{ }}, > ]
    l = l.replace(
      /(\b[a-zA-Z0-9_-]+)\s*(\[\(|\(\[|\[\[|\{\{|\(|\{|\[|>)\s*([^"\]\)\}\n]+?)\s*"([^"\n]+)"\s*([^\]\)\}\n]*?)(\]\)|\)\]|\]\]|\}\}|\)|\}|\])(:::[\w-]+)?/g,
      (match, id, open, lead, inner, trail, close, cls) => {
        const full = [lead.trim(), inner.trim(), trail.trim()].filter(Boolean).join(" ").replace(/"/g, "'");
        return `${id}${open}"${full}"${close}${cls || ""}`;
      }
    );

    // Pattern B: Trailing text outside quotes:
    // nodeId["Click Login" 🟦] -> nodeId["Click Login 🟦"]
    l = l.replace(
      /(\b[a-zA-Z0-9_-]+)\s*(\[\(|\(\[|\[\[|\{\{|\(|\{|\[|>)\s*"([^"\n]+)"\s*([^"\]\)\}\n]+)(\]\)|\)\]|\]\]|\}\}|\)|\}|\])(:::[\w-]+)?/g,
      (match, id, open, inner, trail, close, cls) => {
        const full = [inner.trim(), trail.trim()].filter(Boolean).join(" ").replace(/"/g, "'");
        return `${id}${open}"${full}"${close}${cls || ""}`;
      }
    );

    // Pattern C: Unquoted bracket labels containing parentheses, slashes, or colons
    // nodeId[Process (token) / cache:yes] -> nodeId["Process (token) / cache:yes"]
    l = l.replace(
      /(\b[a-zA-Z0-9_-]+)\s*\[([^"\n\]]*[()/:{}<>,][^"\n\]]*)\](:::[\w-]+)?/g,
      (match, id, inner, cls) => {
        const clean = inner.trim().replace(/"/g, "'");
        return `${id}["${clean}"]${cls || ""}`;
      }
    );

    // Pattern D: Subgraph titles without quotes
    // subgraph FE [Frontend (React)] -> subgraph FE ["Frontend (React)"]
    l = l.replace(/subgraph\s+([a-zA-Z0-9_-]+)\s*\[([^"\]\n]+)\]/g, (match, sgId, title) => {
      const clean = title.trim().replace(/"/g, "'");
      return `subgraph ${sgId} ["${clean}"]`;
    });

    // Pattern E: Subgraph with only quoted string name without ID
    // subgraph "Frontend (React)" -> subgraph sg_frontend ["Frontend (React)"]
    l = l.replace(/subgraph\s+"([^"\n]+)"/g, (match, title) => {
      const safeId = "sg_" + title.toLowerCase().replace(/[^a-z0-9]/g, "_").slice(0, 20);
      return `subgraph ${safeId} ["${title.trim()}"]`;
    });

    // Pattern F: Arrow labels with double quotes
    // -->|"Label"| -> -->|Label|
    l = l.replace(/(-->|-\.->|==>)\|"([^"|\n]+)"\|/g, "$1|$2|");

    // Pattern G: Conversational explanation lines mistakenly inside code
    if (
      trimmed &&
      !trimmed.startsWith("flowchart") &&
      !trimmed.startsWith("graph") &&
      !trimmed.startsWith("subgraph") &&
      !trimmed.startsWith("end") &&
      !trimmed.startsWith("classDef") &&
      !trimmed.startsWith("class ") &&
      !trimmed.startsWith("style ") &&
      !trimmed.startsWith("%%") &&
      !trimmed.includes("-->") &&
      !trimmed.includes("---") &&
      !trimmed.includes("-.->") &&
      !trimmed.includes("==>") &&
      !trimmed.includes("[") &&
      !trimmed.includes("(") &&
      !trimmed.includes("{")
    ) {
      return `%% ${l}`;
    }

    return l;
  });

  let sanitized = cleaned.filter((l) => l.trim() !== "").join("\n");

  // 4. Ensure balanced subgraphs
  const openCount = (sanitized.match(/^\s*subgraph\b/gm) || []).length;
  const closeCount = (sanitized.match(/^\s*end\b/gm) || []).length;
  if (openCount > closeCount) {
    const missing = openCount - closeCount;
    for (let i = 0; i < missing; i++) {
      sanitized += "\nend";
    }
  }

  return sanitized;
}

export default function FlowchartStudio({ workspace, token }) {
  const [prompt, setPrompt] = useState("");
  const [orientation, setOrientation] = useState("TD"); // "TD" | "LR"
  const [loading, setLoading] = useState(false);
  const [flowchartData, setFlowchartData] = useState(null);
  const [viewMode, setViewMode] = useState("diagram"); // "diagram" | "code"
  const [copiedCode, setCopiedCode] = useState(false);
  const [presets, setPresets] = useState([]);
  const [zoomLevel, setZoomLevel] = useState(1);
  const [svgRenderError, setSvgRenderError] = useState(null);
  const [showSources, setShowSources] = useState(false);

  const diagramContainerRef = useRef(null);

  // 1. Fetch Preset Diagrams on Mount
  useEffect(() => {
    if (!workspace?.id) return;
    loadPresets();
    // Initial architecture flowchart based on active workspace repository
    const initialPrompt = workspace?.repository?.name
      ? `Show complete system architecture, request routing, controllers, and data models for ${workspace.repository.name}.`
      : "Show complete application architecture, API gateway routing, and data flow.";
    handleGenerateFlowchart(initialPrompt);
  }, [workspace?.id]);

  const loadPresets = async () => {
    try {
      const res = await fetch(`${API_BASE}/workspaces/${workspace.id}/flowchart/presets`, {
        headers: { Authorization: `Bearer ${token}` }
      });
      const data = await res.json();
      if (res.ok && data.presets) {
        setPresets(data.presets);
      }
    } catch (e) {
      console.warn("Could not load flowchart presets:", e.message);
    }
  };

  // 2. Generate Flowchart from Prompt
  const handleGenerateFlowchart = async (customPrompt) => {
    const query = customPrompt || prompt;
    if (!query || !query.trim() || !workspace?.id) return;

    try {
      setLoading(true);
      setSvgRenderError(null);
      setPrompt(query);

      const res = await fetch(`${API_BASE}/workspaces/${workspace.id}/flowchart/generate`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${token}`
        },
        body: JSON.stringify({
          prompt: query.trim(),
          orientation
        })
      });

      const data = await res.json();
      if (res.ok && data.mermaidCode) {
        setFlowchartData(data);
        renderMermaidSvg(data.mermaidCode);
      } else {
        setSvgRenderError(data.error || "Failed to generate flowchart diagram.");
      }
    } catch (err) {
      console.error("Flowchart generation error:", err);
      setSvgRenderError("Network error connecting to Project Brain.");
    } finally {
      setLoading(false);
    }
  };

  // Clean up any stray error SVG elements mermaid appends to document body
  const cleanupMermaidArtifacts = () => {
    if (typeof document === "undefined") return;
    document.querySelectorAll("[id^='dmermaid-svg-'], [id^='mermaid-svg-'], [id^='dmermaid-fallback-']").forEach((el) => {
      if (el.parentNode === document.body) {
        el.remove();
      }
    });
  };

  // Emergency fallback sanitizer if first pass fails
  const emergencySanitize = (code) => {
    if (!code) return "";
    const clean = sanitizeMermaidCode(code);
    const lines = clean.split("\n");
    let hasHeader = false;
    const finalLines = [];

    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed || trimmed === "%%" || trimmed.startsWith("```")) continue;

      if (/^\s*(flowchart|graph|sequenceDiagram|classDiagram|erDiagram|stateDiagram)\b/i.test(trimmed)) {
        if (!hasHeader) {
          hasHeader = true;
          finalLines.push(trimmed);
        }
        continue;
      }

      // Flatten any bracket nodes to clean plain safe quoted text
      const l = line.replace(/(\b[a-zA-Z0-9_-]+)\s*\[(.*?)\](:::[\w-]+)?/g, (m, id, inner, cls) => {
        const text = inner.replace(/["'\\]/g, "").trim();
        return `${id}["${text}"]${cls || ""}`;
      });

      finalLines.push(l);
    }

    if (!hasHeader) {
      finalLines.unshift("flowchart TD");
    }

    return finalLines.join("\n");
  };

  // 3. Render Mermaid SVG safely
  const renderMermaidSvg = async (code) => {
    if (!code) return;
    cleanupMermaidArtifacts();
    const cleanCode = sanitizeMermaidCode(code);

    try {
      const id = `mermaid-svg-${Date.now()}`;
      const { svg } = await mermaid.render(id, cleanCode);
      if (diagramContainerRef.current) {
        diagramContainerRef.current.innerHTML = svg;
      }
      setSvgRenderError(null);
    } catch (renderErr) {
      console.warn("First Mermaid render attempt failed, trying emergency fallback:", renderErr.message);
      cleanupMermaidArtifacts();

      try {
        const fallbackCode = emergencySanitize(cleanCode);
        const fallbackId = `mermaid-fallback-${Date.now()}`;
        const { svg } = await mermaid.render(fallbackId, fallbackCode);
        if (diagramContainerRef.current) {
          diagramContainerRef.current.innerHTML = svg;
        }
        setSvgRenderError(null);
      } catch (fallbackErr) {
        console.error("Mermaid fallback render error:", fallbackErr);
        cleanupMermaidArtifacts();
        setSvgRenderError(`Mermaid Syntax Render Error: ${renderErr.message}`);
      }
    }
  };

  // Re-render when zooming or orientation changes
  useEffect(() => {
    if (flowchartData?.mermaidCode) {
      renderMermaidSvg(flowchartData.mermaidCode);
    }
  }, [orientation]);

  // 4. Copy Raw Mermaid Code
  const handleCopyCode = () => {
    if (flowchartData?.mermaidCode) {
      navigator.clipboard.writeText(flowchartData.mermaidCode);
      setCopiedCode(true);
      setTimeout(() => setCopiedCode(false), 2000);
    }
  };

  // 5. Export as SVG
  const handleExportSvg = () => {
    if (!diagramContainerRef.current) return;
    const svgEl = diagramContainerRef.current.querySelector("svg");
    if (!svgEl) return;

    const svgData = new XMLSerializer().serializeToString(svgEl);
    const blob = new Blob([svgData], { type: "image/svg+xml;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `axon-flowchart-${Date.now()}.svg`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  // Zoom handlers
  const handleZoomIn = () => setZoomLevel((z) => Math.min(z + 0.2, 2.4));
  const handleZoomOut = () => setZoomLevel((z) => Math.max(z - 0.2, 0.4));
  const handleResetZoom = () => setZoomLevel(1);

  return (
    <div className="flowchart-studio-container">
      {/* Symmetric Top Header Card */}
      <div className="analytics-header-card">
        <div className="analytics-header-main">
          <div className="analytics-eyebrow">
            <span className="analytics-live-dot" />
            AI ARCHITECTURAL VISUALIZER &amp; FLOWCHART STUDIO
          </div>
          <h1 className="analytics-main-title">Architecture Flowchart Studio</h1>
          <div className="analytics-repo-strip">
            <span className="analytics-repo-badge">
              <FolderGit2 size={14} className="text-lime" />
              <strong>{workspace?.repository?.fullName || workspace?.name || "Connected Repo"}</strong>
            </span>
            <span className="analytics-branch-badge">
              branch: <code>{workspace?.repository?.defaultBranch || "main"}</code>
            </span>
            <span className="analytics-meta-pill">
              Mermaid 10.9
            </span>
            <span className="analytics-meta-pill" style={{ color: "#38bdf8", borderColor: "rgba(56,189,248,0.3)" }}>
              Brain RAG Active
            </span>
          </div>
        </div>

        {/* Orientation & Actions */}
        <div className="analytics-header-actions">
          <div className="analytics-health-card">
            <div className="health-grade-circle" style={{ borderColor: "#c8ff3d" }}>
              <span className="health-grade-text" style={{ color: "#c8ff3d", fontSize: "14px" }}>
                100%
              </span>
            </div>
            <div className="health-meta">
              <div className="health-score-val" style={{ color: "#c8ff3d" }}>
                PARSED
              </div>
              <div className="health-label">Diagram Syntax Score</div>
            </div>
          </div>

          <div className="analytics-action-buttons">
            <div
              className="orientation-toggle mono-label"
              style={{
                margin: 0,
                padding: "3px 6px",
                background: "rgba(0,0,0,0.4)",
                borderRadius: "8px",
                border: "1px solid rgba(255,255,255,0.08)",
                display: "flex",
                gap: "4px",
                alignItems: "center"
              }}
            >
              <button
                type="button"
                className={`orient-btn ${orientation === "TD" ? "is-active" : ""}`}
                style={{ padding: "4px 8px", fontSize: "11px" }}
                onClick={() => {
                  setOrientation("TD");
                  if (flowchartData) handleGenerateFlowchart();
                }}
              >
                Top ➔ Bottom
              </button>
              <button
                type="button"
                className={`orient-btn ${orientation === "LR" ? "is-active" : ""}`}
                style={{ padding: "4px 8px", fontSize: "11px" }}
                onClick={() => {
                  setOrientation("LR");
                  if (flowchartData) handleGenerateFlowchart();
                }}
              >
                Left ➔ Right
              </button>
            </div>

            <button
              type="button"
              className="analytics-btn-primary"
              onClick={() => handleGenerateFlowchart()}
              disabled={loading}
              title="Generate new flowchart"
            >
              {loading ? <RefreshCw size={14} className="animate-spin" /> : <Sparkles size={14} />}
              <span>{loading ? "Generating..." : "Generate Flowchart"}</span>
            </button>
          </div>
        </div>
      </div>

      {/* Symmetric Bento KPI Grid: 4 Flowchart Metrics */}
      <div className="analytics-kpi-grid">
        <div className="analytics-kpi-card">
          <div className="kpi-top">
            <span className="kpi-title">RENDERED NODES</span>
            <div className="kpi-icon-wrap">
              <Layers size={16} />
            </div>
          </div>
          <div className="kpi-number">18 Subsystems</div>
          <div className="kpi-sub">
            <span className="kpi-tag-lime">ACTIVE</span>
            <span>Microservices &amp; data stores</span>
          </div>
        </div>

        <div className="analytics-kpi-card">
          <div className="kpi-top">
            <span className="kpi-title">DATA FLOW PATHWAYS</span>
            <div className="kpi-icon-wrap">
              <GitBranch size={16} />
            </div>
          </div>
          <div className="kpi-number">24 Routes</div>
          <div className="kpi-sub">
            <span className="kpi-tag-blue">ROUTED</span>
            <span>REST, WebSockets &amp; RAG</span>
          </div>
        </div>

        <div className="analytics-kpi-card">
          <div className="kpi-top">
            <span className="kpi-title">SECURITY BOUNDARIES</span>
            <div className="kpi-icon-wrap">
              <Shield size={16} />
            </div>
          </div>
          <div className="kpi-number">3 Enclaves</div>
          <div className="kpi-sub">
            <span className="kpi-tag-lime">ISOLATED</span>
            <span>Client, Gateway, Brain Engine</span>
          </div>
        </div>

        <div className="analytics-kpi-card">
          <div className="kpi-top">
            <span className="kpi-title">SYNTAX INTEGRITY</span>
            <div className="kpi-icon-wrap">
              <Code2 size={16} />
            </div>
          </div>
          <div className="kpi-number">100% Sanitized</div>
          <div className="kpi-sub">
            <span className="kpi-tag-blue">AUTO-FIX</span>
            <span>Mermaid.js engine compliant</span>
          </div>
        </div>
      </div>

      {/* Preset Library Chips */}
      {presets.length > 0 && (
        <div className="flowchart-presets-bar">
          <span className="mono-label" style={{ fontSize: "11px", color: "#888" }}>
            QUICK ARCHITECTURE PRESETS:
          </span>
          <div className="flowchart-presets-grid">
            {presets.map((p) => (
              <button
                key={p.id}
                type="button"
                className="flowchart-preset-pill mono-label"
                style={{ "--preset-color": p.color }}
                onClick={() => handleGenerateFlowchart(p.prompt)}
                disabled={loading}
              >
                <span className="preset-dot" style={{ background: p.color }} />
                <span>{p.title}</span>
              </button>
            ))}
          </div>
        </div>
      )}

      {/* Main Prompt Bar */}
      <div className="flowchart-prompt-box">
        <div className="prompt-input-row">
          <Sparkles size={17} color="#c8ff3d" className="prompt-icon" />
          <input
            type="text"
            className="flowchart-prompt-input"
            value={prompt}
            onChange={(e) => setPrompt(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === "Enter" && !loading) handleGenerateFlowchart();
            }}
            placeholder="Ask any architectural flow (e.g. 'Show URL redirection lifecycle', 'Explain how RAG retrieval works', 'Show full client-server microservices flow')..."
          />
          {prompt && (
            <button
              type="button"
              className="clear-prompt-btn mono-label"
              onClick={() => setPrompt("")}
            >
              Clear
            </button>
          )}
        </div>

        <button
          type="button"
          className="button button--lime flowchart-submit-btn"
          onClick={() => handleGenerateFlowchart()}
          disabled={loading || !prompt.trim()}
        >
          {loading ? (
            <RefreshCw size={15} className="spin" />
          ) : (
            <ArrowRight size={15} />
          )}
          <span>{loading ? "Synthesizing Flowchart..." : "Generate Flowchart"}</span>
        </button>
      </div>

      {/* Flowchart Canvas & Studio Viewport */}
      <div className="flowchart-viewport-card">
        {/* Viewport Control Strip */}
        <div className="flowchart-controls-strip">
          <div className="controls-left">
            <button
              type="button"
              className={`view-switch-btn ${viewMode === "diagram" ? "is-active" : ""}`}
              onClick={() => setViewMode("diagram")}
            >
              <GitBranch size={13} color="#c8ff3d" />
              <span>Interactive Diagram</span>
            </button>
            <button
              type="button"
              className={`view-switch-btn ${viewMode === "code" ? "is-active" : ""}`}
              onClick={() => setViewMode("code")}
            >
              <Code2 size={13} color="#38bdf8" />
              <span>Mermaid Code</span>
            </button>
          </div>

          <div className="controls-right">
            {viewMode === "diagram" && (
              <div className="zoom-controls mono-label">
                <button
                  type="button"
                  className="zoom-btn"
                  onClick={handleZoomOut}
                  title="Zoom Out"
                >
                  <ZoomOut size={13} />
                </button>
                <span className="zoom-label">{Math.round(zoomLevel * 100)}%</span>
                <button
                  type="button"
                  className="zoom-btn"
                  onClick={handleZoomIn}
                  title="Zoom In"
                >
                  <ZoomIn size={13} />
                </button>
                <button
                  type="button"
                  className="zoom-btn"
                  onClick={handleResetZoom}
                  title="Reset Zoom"
                >
                  <RotateCcw size={13} />
                </button>
              </div>
            )}

            <button
              type="button"
              className="flowchart-action-btn mono-label"
              onClick={handleCopyCode}
            >
              {copiedCode ? <Check size={12} color="#c8ff3d" /> : <Copy size={12} />}
              <span>{copiedCode ? "Copied" : "Copy Mermaid"}</span>
            </button>

            <button
              type="button"
              className="flowchart-action-btn mono-label"
              onClick={handleExportSvg}
            >
              <Download size={12} />
              <span>Download SVG</span>
            </button>
          </div>
        </div>

        {/* Viewport Content */}
        <div className="flowchart-canvas-area">
          {loading ? (
            <div className="flowchart-loading-state">
              <div className="loading-halo">
                <RefreshCw size={36} className="spin" color="#c8ff3d" />
              </div>
              <h3>Synthesizing Architecture &amp; Logic into Mermaid Flowchart...</h3>
              <p>
                Project Brain is analyzing repository chunks, mapping node dependencies, and
                applying vibrant cyberpunk color coding with Groq 120B.
              </p>
            </div>
          ) : svgRenderError ? (
            <div className="flowchart-error-box">
              <div className="error-box-header">
                <h4>Diagram Rendering Notice</h4>
                <div className="error-box-actions">
                  <button
                    type="button"
                    className="error-repair-btn mono-label"
                    onClick={() => {
                      if (flowchartData?.mermaidCode) {
                        renderMermaidSvg(flowchartData.mermaidCode);
                      }
                    }}
                  >
                    <RefreshCw size={12} />
                    <span>Auto-Repair &amp; Re-render</span>
                  </button>
                  <button
                    type="button"
                    className="error-repair-btn mono-label"
                    onClick={() => setViewMode("code")}
                  >
                    <Code2 size={12} />
                    <span>Inspect Code</span>
                  </button>
                </div>
              </div>
              <p>{svgRenderError}</p>
              {flowchartData?.mermaidCode && (
                <pre className="error-code-preview">
                  <code>{flowchartData.mermaidCode}</code>
                </pre>
              )}
            </div>
          ) : viewMode === "diagram" ? (
            <div className="diagram-scroll-viewport">
              <div
                ref={diagramContainerRef}
                className="mermaid-rendered-svg-wrap"
                style={{
                  transform: `scale(${zoomLevel})`,
                  transformOrigin: "top center",
                  transition: "transform 0.15s ease"
                }}
              />
            </div>
          ) : (
            <div className="mermaid-code-view">
              <div className="code-view-head mono-label">
                <span>VIBRANT MERMAID.JS SYNTAX (COPY-PASTE READY)</span>
                <button type="button" className="copy-code-inline" onClick={handleCopyCode}>
                  {copiedCode ? <Check size={12} color="#c8ff3d" /> : <Copy size={12} />}
                  <span>Copy</span>
                </button>
              </div>
              <pre className="mermaid-pre">
                <code>{flowchartData?.mermaidCode || "No diagram generated yet."}</code>
              </pre>
            </div>
          )}
        </div>

        {/* Architectural Walkthrough & Step-by-Step Breakdown */}
        {flowchartData?.explanation && (
          <div className="flowchart-explanation-drawer">
            <div className="explanation-head mono-label">
              <Sparkles size={12} color="#c8ff3d" />
              <span>ARCHITECTURAL WALKTHROUGH &amp; PROCESS LOGIC</span>
            </div>
            <div className="explanation-body">
              <FormattedAIResponse content={flowchartData.explanation} />
            </div>
          </div>
        )}

        {/* Brain Context Sources */}
        {flowchartData?.relevantChunks && flowchartData.relevantChunks.length > 0 && (
          <div className="flowchart-sources-box">
            <button
              type="button"
              className="sources-toggle mono-label"
              onClick={() => setShowSources(!showSources)}
            >
              <BookOpen size={12} color="#c8ff3d" />
              <span>
                {showSources ? "Hide" : "Inspect"} Brain Sources (
                {flowchartData.relevantChunks.length})
              </span>
            </button>

            {showSources && (
              <div className="sources-list-grid" style={{ marginTop: 10 }}>
                {flowchartData.relevantChunks.map((chunk, idx) => (
                  <div key={idx} className="source-chunk-card">
                    <div className="source-chunk-path mono-label">
                      📄 {chunk.filePath}
                      {chunk.score && (
                        <span className="source-score">
                          match: {(chunk.score * 100).toFixed(0)}%
                        </span>
                      )}
                    </div>
                    <div className="source-chunk-snippet mono-label">
                      {chunk.content?.slice(0, 200)}...
                    </div>
                  </div>
                ))}
              </div>
            )}
          </div>
        )}
      </div>
    </div>
  );
}
