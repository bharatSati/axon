/**
 * Sanitizes and repairs common Mermaid.js syntax errors generated by LLMs.
 * E.g., nodeId[🟦 "Click Login"] -> nodeId["🟦 Click Login"]
 */
export function sanitizeMermaidCode(rawCode) {
  if (!rawCode) return "";
  let code = rawCode;

  // 1. Strip markdown bold and italic asterisks
  code = code.replace(/\*\*/g, "").replace(/(?<!\w)\*(?!\w)/g, "");

  const lines = code.split("\n");
  let hasEncounteredHeader = false;

  const cleaned = lines.map((line) => {
    let l = line.trimEnd();
    const trimmed = l.trim();

    // Filter out markdown code fences or empty comment artifacts
    if (trimmed.startsWith("```") || trimmed === "%%" || trimmed.includes("```mermaid")) {
      return "";
    }

    // Check diagram declaration (flowchart TD, graph TD, sequenceDiagram, etc.)
    if (/^\s*(flowchart\s+(?:TD|TB|BT|RL|LR)|graph\s+(?:TD|TB|BT|RL|LR)|sequenceDiagram|classDiagram|erDiagram|stateDiagram-v2|stateDiagram)\b/i.test(trimmed)) {
      if (!hasEncounteredHeader) {
        hasEncounteredHeader = true;
        return trimmed;
      } else {
        return `%% [Deduplicated duplicate header]: ${trimmed}`;
      }
    }

    // Pattern A: Leading emoji or text outside quotes:
    // nodeId[🟦 "Click Login with GitHub"] -> nodeId["🟦 Click Login with GitHub"]
    // Supports shapes: [ ], ( ), { }, ([ ]), [( )], [[ ]], {{ }}, > ]
    l = l.replace(
      /(\b[a-zA-Z0-9_-]+)\s*(\[\(|\(\[|\[\[|\{\{|\(|\{|\[|>)\s*([^"\]\)\}\n]+?)\s*"([^"\n]+)"\s*([^\]\)\}\n]*?)(\]\)|\)\]|\]\]|\}\}|\)|\}|\])(:::[\w-]+)?/g,
      (match, id, open, lead, inner, trail, close, cls) => {
        const full = [lead.trim(), inner.trim(), trail.trim()].filter(Boolean).join(" ").replace(/"/g, "'");
        return `${id}${open}"${full}"${close}${cls || ""}`;
      }
    );

    // Pattern B: Trailing text outside quotes:
    // nodeId["Click Login" 🟦] -> nodeId["Click Login 🟦"]
    l = l.replace(
      /(\b[a-zA-Z0-9_-]+)\s*(\[\(|\(\[|\[\[|\{\{|\(|\{|\[|>)\s*"([^"\n]+)"\s*([^"\]\)\}\n]+)(\]\)|\)\]|\]\]|\}\}|\)|\}|\])(:::[\w-]+)?/g,
      (match, id, open, inner, trail, close, cls) => {
        const full = [inner.trim(), trail.trim()].filter(Boolean).join(" ").replace(/"/g, "'");
        return `${id}${open}"${full}"${close}${cls || ""}`;
      }
    );

    // Pattern C: Unquoted bracket labels containing parentheses, slashes, or colons
    // nodeId[Process (token) / cache:yes] -> nodeId["Process (token) / cache:yes"]
    l = l.replace(
      /(\b[a-zA-Z0-9_-]+)\s*\[([^"\n\]]*[()/:{}<>,][^"\n\]]*)\](:::[\w-]+)?/g,
      (match, id, inner, cls) => {
        const clean = inner.trim().replace(/"/g, "'");
        return `${id}["${clean}"]${cls || ""}`;
      }
    );

    // Pattern D: Subgraph titles without quotes
    // subgraph FE [Frontend (React)] -> subgraph FE ["Frontend (React)"]
    l = l.replace(/subgraph\s+([a-zA-Z0-9_-]+)\s*\[([^"\]\n]+)\]/g, (match, sgId, title) => {
      const clean = title.trim().replace(/"/g, "'");
      return `subgraph ${sgId} ["${clean}"]`;
    });

    // Pattern E: Subgraph with only quoted string name without ID
    // subgraph "Frontend (React)" -> subgraph sg_frontend ["Frontend (React)"]
    l = l.replace(/subgraph\s+"([^"\n]+)"/g, (match, title) => {
      const safeId = "sg_" + title.toLowerCase().replace(/[^a-z0-9]/g, "_").slice(0, 20);
      return `subgraph ${safeId} ["${title.trim()}"]`;
    });

    // Pattern F: Arrow labels with double quotes
    // -->|"Label"| -> -->|Label|
    l = l.replace(/(-->|-\.->|==>)\|"([^"|\n]+)"\|/g, "$1|$2|");

    // Pattern G: Conversational explanation lines mistakenly inside code
    if (
      trimmed &&
      !trimmed.startsWith("flowchart") &&
      !trimmed.startsWith("graph") &&
      !trimmed.startsWith("subgraph") &&
      !trimmed.startsWith("end") &&
      !trimmed.startsWith("classDef") &&
      !trimmed.startsWith("class ") &&
      !trimmed.startsWith("style ") &&
      !trimmed.startsWith("%%") &&
      !trimmed.includes("-->") &&
      !trimmed.includes("---") &&
      !trimmed.includes("-.->") &&
      !trimmed.includes("==>") &&
      !trimmed.includes("[") &&
      !trimmed.includes("(") &&
      !trimmed.includes("{")
    ) {
      return `%% ${l}`;
    }

    return l;
  });

  return cleaned.filter((l) => l.trim() !== "").join("\n");
}

/**
 * Clean and extract Mermaid code block from raw AI output
 */
function extractMermaidCode(rawText, orientation = "TD") {
  if (!rawText) return "";

  let text = rawText;

  // 1. Try finding ```mermaid ... ``` block
  const match = text.match(/```(?:mermaid)?\s*([\s\S]*?)```/i);
  if (match && match[1]) {
    text = match[1];
  }

  // 2. Strip any leftover backticks
  let lines = text
    .split("\n")
    .map((l) => l.replace(/```(?:mermaid)?/gi, "").trimEnd())
    .filter((l) => {
      const t = l.trim();
      return !t.startsWith("```") && t !== "%%" && !t.includes("```mermaid");
    });

  // 3. Find first valid diagram header
  const headerRegex = /^\s*(flowchart\s+(?:TD|TB|BT|RL|LR)|graph\s+(?:TD|TB|BT|RL|LR)|sequenceDiagram|classDiagram|erDiagram|stateDiagram-v2|stateDiagram)\b/i;
  let firstHeaderIndex = -1;
  let detectedHeader = `flowchart ${orientation}`;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (headerRegex.test(line)) {
      if (firstHeaderIndex === -1) {
        firstHeaderIndex = i;
        detectedHeader = line;
      } else {
        lines[i] = ""; // strip duplicate header
      }
    }
  }

  // Ensure ONE header exists and is positioned at top
  if (firstHeaderIndex === -1) {
    lines.unshift(`flowchart ${orientation}`);
  } else if (firstHeaderIndex > 0) {
    const h = lines[firstHeaderIndex];
    lines.splice(firstHeaderIndex, 1);
    lines.unshift(h);
  }

  let code = lines.join("\n").trim();

  // 4. Sanitize syntax to avoid Mermaid parser crash
  code = sanitizeMermaidCode(code);

  // 5. Ensure balanced subgraphs
  const openCount = (code.match(/^\s*subgraph\b/gm) || []).length;
  const closeCount = (code.match(/^\s*end\b/gm) || []).length;
  if (openCount > closeCount) {
    const missing = openCount - closeCount;
    for (let i = 0; i < missing; i++) {
      code += "\nend";
    }
  }

  // 6. Ensure colorful class definitions are appended if not present
  if (!code.includes("classDef client")) {
    code = `${code}\n\n${COLORFUL_MERMAID_CLASSES}`;
  }

  return code;
}

/**
 * Generate an architectural Mermaid flowchart from user prompt + Project Brain RAG context
 */
export async function generateFlowchartDiagram(workspaceId, prompt, options = {}) {
  const { detailLevel = "comprehensive", orientation = "TD" } = options;

  const workspace = await Workspace.findOne({ id: workspaceId }).lean();
  const repoName = workspace?.repository?.fullName || workspace?.name || "Axon Workspace";

  // 1. Retrieve RAG chunks from Project Brain related to this prompt
  let ragChunks = [];
  try {
    const ragRes = await queryWorkspaceBrain(workspaceId, prompt, { topK: 5 });
    if (ragRes?.results) ragChunks = ragRes.results;
  } catch (err) {
    console.warn("RAG query notice for flowchart generation:", err.message);
  }

  const formattedContext = ragChunks
    .map((c, i) => `--- [CODE CONTEXT ${i + 1}: ${c.filePath}] ---\n${c.content}`)
    .join("\n\n");

  const systemPrompt = `You are the Axon Architectural Visualizer and System Flowchart Engineer.
Your task is to convert developer prompts and software codebase logic into ULTRA-VIBRANT, COLORFUL, and COMPILE-READY Mermaid.js flowcharts.

CRITICAL MERMAID SYNTAX RULES (Violating these will crash the diagram parser):
1. Always start with: \`flowchart ${orientation}\`
2. Group related stages into \`subgraph SubgraphId ["Clean Title with Emoji"] ... end\` blocks.
   Example: \`subgraph FE ["🖥️ Frontend Layer"]\`
3. Node labels MUST be enclosed in double quotes immediately after the bracket:
   CORRECT EXAMPLES:
   - \`FE_Login["🟦 Click Login with GitHub"]:::client\`
   - \`DB_User[("🗄️ Users Collection")]:::db\`
   - \`Dec_Valid{"❓ Token Valid?"}:::decision\`
   - \`SVC_Auth(["🔐 Auth Service"]):::auth\`
   FATAL SYNTAX ERRORS (NEVER DO THIS):
   - NEVER put emojis or text outside quotes: \`FE_Login[🟦 "Click Login"]\` is INVALID and crashes the parser! The opening quote MUST follow the opening bracket: \`FE_Login["🟦 Click Login"]\`.
   - NEVER use markdown formatting like **bold** or *italic* inside node labels: use plain text only.
   - NEVER put unquoted parentheses inside square brackets: \`A[Login (GitHub)]\` is INVALID. Always use quotes: \`A["Login (GitHub)"]\`.
   - NEVER put double quotes inside labels. Use single quotes if necessary: \`A["Send 'Bearer' Token"]\`.
4. Apply colorful class definitions to every node using \`:::className\`:
   - \`:::client\` for frontend, browsers, user inputs (cyan neon)
   - \`:::gateway\` for API gateway, ingress, router (indigo neon)
   - \`:::auth\` for authentication, tokens, security checks (purple neon)
   - \`:::logic\` for controllers, domain services, workers (emerald green)
   - \`:::ai\` for LLM, Groq, Project Brain RAG, vector retrieval (lime neon)
   - \`:::db\` for databases, schemas, MongoDB, storage (amber gold)
   - \`:::decision\` for conditionals, checks, validation branches (orange gold)
   - \`:::success\` for 200 OK, successful responses, redirects (green)
   - \`:::error\` for 401, 403, 404, 500 rejections (red)
5. Include descriptive transition arrows: \`A -->|Valid Token| B\` or \`C -->|No| D\` (no double quotes inside |...|)
6. Never output broken syntax or raw HTML tags inside node labels.
7. Wrap your entire diagram in a single \`\`\`mermaid code fence.
8. Follow the diagram with a concise 3-5 bullet point architectural walkthrough explaining what happens at each step in plain English without symbol clutter.`;

  const userPrompt = `REPOSITORY / WORKSPACE: ${repoName}

USER ARCHITECTURAL REQUEST / PROMPT:
"${prompt}"

ENGINEERING REPOSITORY CONTEXT (PROJECT BRAIN RAG):
${formattedContext || "Standard full-stack client-server architecture with React frontend, Express API gateway, JWT auth, MongoDB Atlas, and Groq 120B Project Brain."}

TASK:
Generate a vibrant, colorful, and accurate Mermaid flowchart diagram depicting this exact architecture and process flow, followed by a concise step-by-step walkthrough.`;

  try {
    const rawResponse = await callGroqChat(
      [
        { role: "system", content: systemPrompt },
        { role: "user", content: userPrompt }
      ],
      { temperature: 0.25, max_tokens: 1500 }
    );

    if (!rawResponse) {
      throw new Error("AI service returned empty response");
    }

    // Extract Mermaid block and explanation text
    const mermaidMatch = rawResponse.match(/```(?:mermaid)?\s*([\s\S]*?)\s*```/i);
    const mermaidCode = extractMermaidCode(mermaidMatch ? mermaidMatch[1] : rawResponse, orientation);

    // Everything after the code block is the explanation walkthrough
    let explanation = "";
    if (mermaidMatch) {
      const parts = rawResponse.split(/```(?:mermaid)?[\s\S]*?```/i);
      explanation = parts[parts.length - 1]?.trim() || "";
    } else {
      explanation = "Architectural flowchart synthesized from repository source files and Project Brain.";
    }

    return {
      success: true,
      prompt,
      title: deriveTitleFromPrompt(prompt),
      mermaidCode,
      explanation: sanitizeAIOutput(explanation),
      relevantChunks: ragChunks
    };
  } catch (err) {
    console.error("generateFlowchartDiagram error:", err);
    throw new Error(`Failed to generate architectural flowchart: ${err.message}`);
  }
}

/**
 * Derive clean title from prompt
 */
function deriveTitleFromPrompt(prompt = "") {
  const p = prompt.trim();
  if (p.length < 50) return p;
  const firstSentence = p.split(/[.?!]/)[0];
  return firstSentence.slice(0, 50) + "...";
}

